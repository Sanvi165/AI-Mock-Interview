"""Builds the downloadable interview report (Markdown)."""
from app.schemas.interview import SessionDetail

CRITERION_NAMES = {
    "relevance": "Relevance",
    "correctness": "Correctness",
    "clarity": "Clarity",
    "completeness": "Completeness",
    "problem_solving": "Problem solving",
}


def _source_text(source: str) -> str:
    if source == "gemini":
        return "AI-generated estimate"
    return "Rule-based estimate (keyword and length checks), not an expert judgement"


def _bullets(items: list[str]) -> list[str]:
    return [f"- {item}" for item in items] if items else ["- None"]


def build_markdown_report(detail: SessionDetail) -> str:
    lines: list[str] = []
    lines.append("# Mock Interview Report")
    lines.append("")
    lines.append(f"- **Role:** {detail.role}")
    lines.append(f"- **Domain:** {detail.domain}")
    lines.append(f"- **Experience level:** {detail.experience_level}")
    lines.append(f"- **Interview type:** {detail.interview_type}")
    lines.append(f"- **Date:** {detail.created_at[:10]}")
    lines.append(f"- **Overall score:** {detail.overall_score}/100")
    lines.append("")
    lines.append(
        "> **How to read this report:** Word counts, filler words and speaking pace are "
        "*measured*. Rubric scores and feedback are *estimates* (labelled per question). "
        "This report does not analyse facial expressions, emotions or personality. "
        "Webcam recordings are never stored by this app."
    )
    lines.append("")

    if detail.summary:
        s = detail.summary
        lines.append("## Summary")
        lines.append(f"- Answered {s.answered} of {s.total_questions} questions.")
        lines.append("")
        lines.append("| Criterion | Average (0-10) |")
        lines.append("|---|---|")
        for key, value in s.criterion_averages.items():
            lines.append(f"| {CRITERION_NAMES.get(key, key)} | {value} |")
        lines.append("")
        lines.append(f"- **Strong topics:** {', '.join(s.strong_topics) or 'None yet'}")
        lines.append(f"- **Topics to revise:** {', '.join(s.weak_topics) or 'None'}")
        lines.append("")

    lines.append("## Question-by-question review")
    for number, item in enumerate(detail.results, start=1):
        q = item.question
        kind = {"followup": " (follow-up)", "simpler": " (simpler question)"}.get(q.kind, "")
        lines.append("")
        lines.append(f"### Q{number}{kind}: {q.text}")
        lines.append(f"*Topic: {q.topic} | Difficulty: {q.difficulty}*")
        lines.append("")
        if item.evaluation is None:
            lines.append("_Not answered._")
            continue
        ev = item.evaluation
        lines.append(f"**Your answer:** {item.answer_text}")
        lines.append("")
        lines.append(f"**Score:** {ev.overall_score}/100 ({ev.label}) - {_source_text(ev.source)}")
        lines.append("")
        lines.append("| Criterion | Score (0-10) |")
        lines.append("|---|---|")
        for key in CRITERION_NAMES:
            lines.append(f"| {CRITERION_NAMES[key]} | {getattr(ev.scores, key)} |")
        lines.append("")
        m = ev.metrics
        pace = f"{m.words_per_minute} words/min" if m.words_per_minute else "not measured (typed answer)"
        lines.append(
            f"**Measured:** {m.word_count} words, {m.filler_count} filler words, speaking pace {pace}."
        )
        lines.append("")
        lines.append("**Strengths**")
        lines.extend(_bullets(ev.feedback.strengths))
        lines.append("")
        lines.append("**Weaknesses**")
        lines.extend(_bullets(ev.feedback.weaknesses))
        lines.append("")
        lines.append("**Missing concepts**")
        lines.extend(_bullets(ev.feedback.missing_concepts))
        lines.append("")
        lines.append("**Suggested improvements**")
        lines.extend(_bullets(ev.feedback.improvements))
        lines.append("")
        lines.append(f"**Example of a stronger answer:** {ev.feedback.stronger_answer or 'Not available.'}")

    lines.append("")
    lines.append("---")
    lines.append("Generated by AI-Powered Mock Interview. Scores are practice feedback, not hiring decisions.")
    return "\n".join(lines)